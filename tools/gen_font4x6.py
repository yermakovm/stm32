#!/usr/bin/env python3
"""Generate Core/Src/font4x6.c from ASCII-art glyphs.

Each glyph is 4 columns x 6 rows, '#' = lit pixel.  Data is stored
column-major with bit0 = top row, exactly like font5x7, so a glyph is
one 4-byte copy per framebuffer column.

Why a second font: the 5x7 table advances 6 px per character, so the
sensor line "T:23.4°C RH:45% P:1013hPa" (25 chars) would need 150 px on
a 128 px panel.  At 5 px/char the same line is 125 px and fits.

Usage: python3 tools/gen_font4x6.py > Core/Src/font4x6.c
"""

import sys

# Caps only (the 5x7 table folds lowercase to caps too) + digits + the
# punctuation a status line can need.  Codes without art are emitted as
# blanks, so an unsupported character is a gap, never garbage.
