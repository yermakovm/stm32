# Same pseudo-glyph code as in font5x7 (see tools/gen_font.py).
DEGREE = 0x7F
ART_DEGREE = ".##.\n#..#\n.##.\n....\n....\n...."

FIRST = 0x20
LAST = 0x7F
GLYPH_W = 4
GLYPH_H = 6


def pack(art: str) -> list[int]:
    rows = art.split("\n")
    assert len(rows) == GLYPH_H, f"{len(rows)} rows for:\n{art}"
    cols = [0] * GLYPH_W
    for r, line in enumerate(rows):
        assert len(line) == GLYPH_W, f"row width {line!r} in:\n{art}"
        for c, ch in enumerate(line):
            if ch == "#":
                cols[c] |= 1 << r
            elif ch != ".":
                raise AssertionError(f"bad char {ch!r} in:\n{art}")
    return cols


def main() -> None:
    out = [
        "/* Generated by tools/gen_font4x6.py - do not edit by hand. */",
        "#include <stddef.h>",
        "#include \"font4x6.h\"",
        "",
        "/* Column-major, bit0 = top row. Codes without art are blank. */",
        "static const uint8_t FONT4X6[FONT4X6_GLYPH_COUNT][FONT4X6_WIDTH] = {",
    ]
    for code in range(FIRST, LAST + 1):
        if code == DEGREE:
            art = ART_DEGREE
            label = "deg"
        else:
            art = ART.get(chr(code), ART[" "])
            label = repr(chr(code)).replace("'", "")
        data = ", ".join(f"0x{b:02X}" for b in pack(art))
        out.append(f"    {{{data}}},  /* {label} */")
    out += [
        "};",
        "",
        "const uint8_t *font4x6_glyph(char ch)",
        "{",
        "    unsigned c = (unsigned char)ch;",
        "",
        "    if (c >= 'a' && c <= 'z') {   /* no lowercase: fold to caps */",
        "        c -= (unsigned char)('a' - 'A');",
        "    }",
        "    if (c < FONT4X6_FIRST || c > FONT4X6_LAST) {",
        "        return NULL;",
        "    }",
        "    return &FONT4X6[c - FONT4X6_FIRST][0];",
        "}",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
